--Siguen los triggers

--Trigger antes de insertar detalle de venta
--Este trigger hace 3 cosas:

--Busca el precio de venta actual del producto
--Verifica que haya stock suficiente
--Calcula automáticamente el subtotal

CREATE OR REPLACE TRIGGER TRG_BI_DETALLE_VENTAS
BEFORE INSERT ON DETALLE_VENTAS
FOR EACH ROW
DECLARE
    V_PRECIO_VENTA PRODUCTOS.PRECIO_VENTA%TYPE;
    V_STOCK PRODUCTOS.STOCK%TYPE;
BEGIN
    SELECT PRECIO_VENTA, STOCK
    INTO V_PRECIO_VENTA, V_STOCK
    FROM PRODUCTOS
    WHERE ID_PRODUCTO = :NEW.ID_PRODUCTO;

    IF V_STOCK < :NEW.CANTIDAD THEN
        RAISE_APPLICATION_ERROR(-20001, 'No hay stock suficiente para realizar la venta.');
    END IF;

    :NEW.PRECIO_UNITARIO := V_PRECIO_VENTA;
    :NEW.SUBTOTAL := :NEW.CANTIDAD * V_PRECIO_VENTA;
END;
/

--Trigger después de insertar detalle de venta
--Este trigger hace:

--Descuenta el stock
--Registra la salida en MOVIMIENTOS_INVENTARIO
--Suma el subtotal al total de la venta

CREATE OR REPLACE TRIGGER TRG_AI_DETALLE_VENTAS
AFTER INSERT ON DETALLE_VENTAS
FOR EACH ROW
DECLARE
    V_STOCK_ANTERIOR PRODUCTOS.STOCK%TYPE;
    V_ID_USUARIO VENTAS.ID_USUARIO%TYPE;
BEGIN
    SELECT STOCK
    INTO V_STOCK_ANTERIOR
    FROM PRODUCTOS
    WHERE ID_PRODUCTO = :NEW.ID_PRODUCTO;

    SELECT ID_USUARIO
    INTO V_ID_USUARIO
    FROM VENTAS
    WHERE ID_VENTA = :NEW.ID_VENTA;

    UPDATE PRODUCTOS
    SET STOCK = STOCK - :NEW.CANTIDAD
    WHERE ID_PRODUCTO = :NEW.ID_PRODUCTO;

    INSERT INTO MOVIMIENTOS_INVENTARIO (
        ID_MOVIMIENTO,
        ID_PRODUCTO,
        ID_USUARIO,
        TIPO_MOVIMIENTO,
        CANTIDAD,
        STOCK_ANTERIOR,
        STOCK_NUEVO,
        DESCRIPCION,
        ID_VENTA
    )
    VALUES (
        SQ_MOVIMIENTOS_INVENTARIO.NEXTVAL,
        :NEW.ID_PRODUCTO,
        V_ID_USUARIO,
        'SALIDA',
        :NEW.CANTIDAD,
        V_STOCK_ANTERIOR,
        V_STOCK_ANTERIOR - :NEW.CANTIDAD,
        'Salida automática por venta',
        :NEW.ID_VENTA
    );

    UPDATE VENTAS
    SET TOTAL = TOTAL + :NEW.SUBTOTAL
    WHERE ID_VENTA = :NEW.ID_VENTA;
END;
/



--Luego los triggers de compra:

--Trigger antes de insertar detalle de compra
--Este trigger calcula automáticamente el subtotal de una compra

--Si no mandamos precio unitario, usa el PRECIO_COMPRA del producto

CREATE OR REPLACE TRIGGER TRG_BI_DETALLE_COMPRAS
BEFORE INSERT ON DETALLE_COMPRAS
FOR EACH ROW
DECLARE
    V_PRECIO_COMPRA PRODUCTOS.PRECIO_COMPRA%TYPE;
BEGIN
    SELECT PRECIO_COMPRA
    INTO V_PRECIO_COMPRA
    FROM PRODUCTOS
    WHERE ID_PRODUCTO = :NEW.ID_PRODUCTO;

    IF :NEW.PRECIO_UNITARIO IS NULL OR :NEW.PRECIO_UNITARIO = 0 THEN
        :NEW.PRECIO_UNITARIO := V_PRECIO_COMPRA;
    END IF;

    :NEW.SUBTOTAL := :NEW.CANTIDAD * :NEW.PRECIO_UNITARIO;
END;
/


