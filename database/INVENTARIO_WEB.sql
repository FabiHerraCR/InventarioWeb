--Sincronizar con lo de antes:
INSERT INTO MOVIMIENTOS_INVENTARIO (
    ID_MOVIMIENTO,
    ID_PRODUCTO,
    ID_USUARIO,
    TIPO_MOVIMIENTO,
    CANTIDAD,
    STOCK_ANTERIOR,
    STOCK_NUEVO,
    DESCRIPCION,
    ID_VENTA
)
SELECT
    SQ_MOVIMIENTOS_INVENTARIO.NEXTVAL,
    DV.ID_PRODUCTO,
    V.ID_USUARIO,
    'SALIDA',
    DV.CANTIDAD,
    P.STOCK,
    P.STOCK - DV.CANTIDAD,
    'Salida de inventario por venta de prueba',
    V.ID_VENTA
FROM DETALLE_VENTAS DV
INNER JOIN VENTAS V ON DV.ID_VENTA = V.ID_VENTA
INNER JOIN PRODUCTOS P ON DV.ID_PRODUCTO = P.ID_PRODUCTO
WHERE V.ID_VENTA = 1;

--Descontamos del stock
UPDATE PRODUCTOS P
SET P.STOCK = P.STOCK - (
    SELECT NVL(SUM(DV.CANTIDAD), 0)
    FROM DETALLE_VENTAS DV
    WHERE DV.ID_PRODUCTO = P.ID_PRODUCTO
    AND DV.ID_VENTA = 1
)
WHERE EXISTS (
    SELECT 1
    FROM DETALLE_VENTAS DV
    WHERE DV.ID_PRODUCTO = P.ID_PRODUCTO
    AND DV.ID_VENTA = 1
);

COMMIT;


--Luego se registra la entrada por compra:
INSERT INTO MOVIMIENTOS_INVENTARIO (
    ID_MOVIMIENTO,
    ID_PRODUCTO,
    ID_USUARIO,
    TIPO_MOVIMIENTO,
    CANTIDAD,
    STOCK_ANTERIOR,
    STOCK_NUEVO,
    DESCRIPCION,
    ID_COMPRA
)
SELECT
    SQ_MOVIMIENTOS_INVENTARIO.NEXTVAL,
    DC.ID_PRODUCTO,
    C.ID_USUARIO,
    'ENTRADA',
    DC.CANTIDAD,
    P.STOCK,
    P.STOCK + DC.CANTIDAD,
    'Entrada de inventario por compra de prueba',
    C.ID_COMPRA
FROM DETALLE_COMPRAS DC
INNER JOIN COMPRAS C ON DC.ID_COMPRA = C.ID_COMPRA
INNER JOIN PRODUCTOS P ON DC.ID_PRODUCTO = P.ID_PRODUCTO
WHERE C.ID_COMPRA = 1;

--Se aumenta el stock por esa compra
UPDATE PRODUCTOS P
SET P.STOCK = P.STOCK + (
    SELECT NVL(SUM(DC.CANTIDAD), 0)
    FROM DETALLE_COMPRAS DC
    WHERE DC.ID_PRODUCTO = P.ID_PRODUCTO
    AND DC.ID_COMPRA = 1
)
WHERE EXISTS (
    SELECT 1
    FROM DETALLE_COMPRAS DC
    WHERE DC.ID_PRODUCTO = P.ID_PRODUCTO
    AND DC.ID_COMPRA = 1
);

COMMIT;


