--procedimientos para anular ventas y compras:

--Procedimiento para anular venta
--Cambia VENTAS.ESTADO a ANULADA.
--el stock de los productos vendidos.
--Registra movimiento de inventario tipo ENTRADA.

CREATE OR REPLACE PROCEDURE SP_DEL_VENTA (
    P_ID_VENTA IN VENTAS.ID_VENTA%TYPE
)
AS
    V_ESTADO VENTAS.ESTADO%TYPE;
    V_ID_USUARIO VENTAS.ID_USUARIO%TYPE;
    V_STOCK_ANTERIOR PRODUCTOS.STOCK%TYPE;
BEGIN
    SELECT ESTADO, ID_USUARIO
    INTO V_ESTADO, V_ID_USUARIO
    FROM VENTAS
    WHERE ID_VENTA = P_ID_VENTA;

    IF V_ESTADO = 'ANULADA' THEN
        RAISE_APPLICATION_ERROR(-20020, 'La venta ya se encuentra anulada.');
    END IF;

    FOR DET IN (
        SELECT ID_PRODUCTO, CANTIDAD
        FROM DETALLE_VENTAS
        WHERE ID_VENTA = P_ID_VENTA
    ) LOOP

        SELECT STOCK
        INTO V_STOCK_ANTERIOR
        FROM PRODUCTOS
        WHERE ID_PRODUCTO = DET.ID_PRODUCTO;

        UPDATE PRODUCTOS
        SET STOCK = STOCK + DET.CANTIDAD
        WHERE ID_PRODUCTO = DET.ID_PRODUCTO;

        INSERT INTO MOVIMIENTOS_INVENTARIO (
            ID_MOVIMIENTO,
            ID_PRODUCTO,
            ID_USUARIO,
            TIPO_MOVIMIENTO,
            CANTIDAD,
            STOCK_ANTERIOR,
            STOCK_NUEVO,
            DESCRIPCION,
            ID_VENTA
        )
        VALUES (
            SQ_MOVIMIENTOS_INVENTARIO.NEXTVAL,
            DET.ID_PRODUCTO,
            V_ID_USUARIO,
            'ENTRADA',
            DET.CANTIDAD,
            V_STOCK_ANTERIOR,
            V_STOCK_ANTERIOR + DET.CANTIDAD,
            'Entrada por anulacion de venta',
            P_ID_VENTA
        );

    END LOOP;

    UPDATE VENTAS
    SET ESTADO = 'ANULADA'
    WHERE ID_VENTA = P_ID_VENTA;
END;
/



--Procedimiento para anular compra
--Cambia COMPRAS.ESTADO a ANULADA.
--Descuenta del stock lo que se había comprado.
--Registra movimiento de inventario tipo SALIDA.
CREATE OR REPLACE PROCEDURE SP_DEL_COMPRA (
    P_ID_COMPRA IN COMPRAS.ID_COMPRA%TYPE
)
AS
    V_ESTADO COMPRAS.ESTADO%TYPE;
    V_ID_USUARIO COMPRAS.ID_USUARIO%TYPE;
    V_STOCK_ANTERIOR PRODUCTOS.STOCK%TYPE;
BEGIN
    SELECT ESTADO, ID_USUARIO
    INTO V_ESTADO, V_ID_USUARIO
    FROM COMPRAS
    WHERE ID_COMPRA = P_ID_COMPRA;

    IF V_ESTADO = 'ANULADA' THEN
        RAISE_APPLICATION_ERROR(-20021, 'La compra ya se encuentra anulada.');
    END IF;

    FOR DET IN (
        SELECT ID_PRODUCTO, CANTIDAD
        FROM DETALLE_COMPRAS
        WHERE ID_COMPRA = P_ID_COMPRA
    ) LOOP

        SELECT STOCK
        INTO V_STOCK_ANTERIOR
        FROM PRODUCTOS
        WHERE ID_PRODUCTO = DET.ID_PRODUCTO;

        IF V_STOCK_ANTERIOR < DET.CANTIDAD THEN
            RAISE_APPLICATION_ERROR(-20022, 'No hay stock suficiente para anular la compra.');
        END IF;

        UPDATE PRODUCTOS
        SET STOCK = STOCK - DET.CANTIDAD
        WHERE ID_PRODUCTO = DET.ID_PRODUCTO;

        INSERT INTO MOVIMIENTOS_INVENTARIO (
            ID_MOVIMIENTO,
            ID_PRODUCTO,
            ID_USUARIO,
            TIPO_MOVIMIENTO,
            CANTIDAD,
            STOCK_ANTERIOR,
            STOCK_NUEVO,
            DESCRIPCION,
            ID_COMPRA
        )
        VALUES (
            SQ_MOVIMIENTOS_INVENTARIO.NEXTVAL,
            DET.ID_PRODUCTO,
            V_ID_USUARIO,
            'SALIDA',
            DET.CANTIDAD,
            V_STOCK_ANTERIOR,
            V_STOCK_ANTERIOR - DET.CANTIDAD,
            'Salida por anulacion de compra',
            P_ID_COMPRA
        );

    END LOOP;

    UPDATE COMPRAS
    SET ESTADO = 'ANULADA'
    WHERE ID_COMPRA = P_ID_COMPRA;
END;
/

